from __future__ import annotations

from codecforge.schema import CodecSpec, validate_spec


_MODULE_TEMPLATE = '''"""Standalone zero-dependency Python codec generated by codecforge."""
from __future__ import annotations

import math
import struct
import zlib
from typing import Any

SPEC_DICT: dict[str, Any] = {spec_repr}

_SCALAR_FMT: dict[str, tuple[str, int, bool]] = {{
    "u8": ("<B", 1, True),    "i8": ("<b", 1, True),
    "u16le": ("<H", 2, True), "u16be": (">H", 2, True),
    "i16le": ("<h", 2, True), "i16be": (">h", 2, True),
    "u32le": ("<I", 4, True), "u32be": (">I", 4, True),
    "i32le": ("<i", 4, True), "i32be": (">i", 4, True),
    "u64le": ("<Q", 8, True), "u64be": (">Q", 8, True),
    "i64le": ("<q", 8, True), "i64be": (">q", 8, True),
    "f32le": ("<f", 4, False), "f32be": (">f", 4, False),
    "f64le": ("<d", 8, False), "f64be": (">d", 8, False),
}}

_UNSIGNED_MAX: dict[str, int] = {{
    "u8": 0xFF,
    "u16le": 0xFFFF, "u16be": 0xFFFF,
    "u32le": 0xFFFFFFFF, "u32be": 0xFFFFFFFF,
    "u64le": 0xFFFFFFFFFFFFFFFF, "u64be": 0xFFFFFFFFFFFFFFFF,
}}

_SIGNED_BOUNDS: dict[str, tuple[int, int]] = {{
    "i8": (-128, 127),
    "i16le": (-32768, 32767), "i16be": (-32768, 32767),
    "i32le": (-2147483648, 2147483647), "i32be": (-2147483648, 2147483647),
    "i64le": (-9223372036854775808, 9223372036854775807),
    "i64be": (-9223372036854775808, 9223372036854775807),
}}


def _resolve_span(fields: list[dict[str, Any]], expr: str) -> list[str]:
    names = [f["name"] for f in fields]
    idx_map = {{name: i for i, name in enumerate(names)}}
    if ".." in expr:
        start_name, end_name = expr.split("..", 1)
        return names[idx_map[start_name] : idx_map[end_name] + 1]
    return [expr]


def _decode_fields(
    fields: list[dict[str, Any]], data: bytes, pos: int
) -> tuple[dict[str, Any], int]:
    out: dict[str, Any] = {{}}
    spans: dict[str, tuple[int, int]] = {{}}

    for f in fields:
        name = f["name"]
        kind = f["kind"]
        start = pos

        if kind == "magic":
            expected = bytes.fromhex(f["magic_hex"])
            end = pos + len(expected)
            if end > len(data) or data[pos:end] != expected:
                raise ValueError(f"Magic mismatch on '{{name}}' at 0x{{pos:x}}")
            out[name] = expected.hex().upper()
            pos = end
        elif kind == "scalar":
            fmt, width, is_int = _SCALAR_FMT[f["scalar_type"]]
            if pos + width > len(data):
                raise ValueError(f"Truncated scalar '{{name}}' at 0x{{pos:x}}")
            val = struct.unpack_from(fmt, data, pos)[0]
            if not is_int and math.isnan(val):
                raise ValueError(f"NaN float in '{{name}}' at 0x{{pos:x}}")
            out[name] = val
            pos += width
        elif kind == "fixed_bytes":
            size = int(f["size"])
            if pos + size > len(data):
                raise ValueError(f"Truncated fixed_bytes '{{name}}' at 0x{{pos:x}}")
            out[name] = data[pos : pos + size]
            pos += size
        elif kind == "fixed_str":
            size = int(f["size"])
            if pos + size > len(data):
                raise ValueError(f"Truncated fixed_str '{{name}}' at 0x{{pos:x}}")
            raw = data[pos : pos + size]
            pad = bytes.fromhex(f.get("pad_byte_hex", "00"))
            idx = raw.find(pad)
            if idx != -1 and any(b != pad[0] for b in raw[idx:]):
                raise ValueError(f"Non-canonical padding in fixed_str '{{name}}'")
            content = raw[:idx] if idx != -1 else raw
            out[name] = content.decode(f.get("encoding", "utf-8"), errors="strict")
            pos += size
        elif kind == "cstr":
            nul = data.find(b"\\x00", pos)
            if nul == -1:
                raise ValueError(f"Unterminated cstr '{{name}}' at 0x{{pos:x}}")
            out[name] = data[pos:nul].decode(f.get("encoding", "utf-8"), errors="strict")
            pos = nul + 1
        elif kind in ("var_str", "var_bytes"):
            n = int(out[f["length_field"]])
            if n < 0 or pos + n > len(data):
                raise ValueError(f"Truncated {{kind}} '{{name}}' at 0x{{pos:x}}")
            raw = data[pos : pos + n]
            out[name] = (
                raw.decode(f.get("encoding", "utf-8"), errors="strict")
                if kind == "var_str"
                else raw
            )
            pos += n
        elif kind == "array":
            cnt = int(out[f["count_field"]])
            items: list[dict[str, Any]] = []
            for _ in range(cnt):
                item, pos = _decode_fields(f["item_fields"], data, pos)
                items.append(item)
            out[name] = items
        elif kind == "bytes_rest":
            out[name] = data[pos:]
            pos = len(data)
        else:
            raise ValueError(f"Unsupported field kind: {{kind}}")

        spans[name] = (start, pos)

    for f in fields:
        if f["kind"] == "scalar" and f.get("crc32_of"):
            targets = _resolve_span(fields, f["crc32_of"])
            covered = b"".join(data[spans[t][0] : spans[t][1]] for t in targets)
            expected_crc = zlib.crc32(covered) & 0xFFFFFFFF
            if out[f["name"]] != expected_crc:
                raise ValueError(f"CRC32 mismatch on '{{f['name']}}'")

    return out, pos


def _pack_scalar(f: dict[str, Any], val: Any) -> bytes:
    st = f["scalar_type"]
    fmt, _, is_int = _SCALAR_FMT[st]
    if is_int:
        if isinstance(val, bool) or not isinstance(val, int):
            raise ValueError(f"Scalar '{{f['name']}}' expects int")
        if st in _UNSIGNED_MAX:
            if val < 0 or val > _UNSIGNED_MAX[st]:
                raise ValueError(f"Scalar '{{f['name']}}' out of unsigned bounds")
        else:
            lo, hi = _SIGNED_BOUNDS[st]
            if val < lo or val > hi:
                raise ValueError(f"Scalar '{{f['name']}}' out of signed bounds")
    else:
        if isinstance(val, bool) or not isinstance(val, (int, float)):
            raise ValueError(f"Scalar '{{f['name']}}' expects finite float")
        try:
            fval = float(val)
        except OverflowError as exc:
            raise ValueError(f"Failed packing scalar '{{f['name']}}': {{exc}}") from exc
        if not math.isfinite(fval):
            raise ValueError(f"Scalar '{{f['name']}}' expects finite float")
        val = fval
    try:
        return struct.pack(fmt, val)
    except (struct.error, OverflowError) as exc:
        raise ValueError(f"Failed packing scalar '{{f['name']}}': {{exc}}") from exc


def _require_field(obj: dict[str, Any], name: str) -> Any:
    if name not in obj:
        raise ValueError(f"Missing required field '{{name}}'")
    return obj[name]


def _encode_fields(fields: list[dict[str, Any]], obj: dict[str, Any]) -> bytes:
    if not isinstance(obj, dict):
        raise ValueError("Object to encode must be a dictionary")
    chunks: dict[str, bytes] = {{}}

    for f in fields:
        name = f["name"]
        kind = f["kind"]
        if kind == "magic":
            chunks[name] = bytes.fromhex(f["magic_hex"])
        elif kind == "scalar":
            if f.get("count_of"):
                items = _require_field(obj, f["count_of"])
                if not isinstance(items, list):
                    raise ValueError(f"count_of target '{{f['count_of']}}' must be a list")
                chunks[name] = _pack_scalar(f, len(items))
            elif f.get("length_of") or f.get("crc32_of"):
                chunks[name] = b""
            else:
                chunks[name] = _pack_scalar(f, _require_field(obj, name))
        elif kind == "fixed_bytes":
            raw_val = _require_field(obj, name)
            if not isinstance(raw_val, (bytes, bytearray)):
                raise ValueError(f"fixed_bytes '{{name}}' must be bytes/bytearray")
            b = bytes(raw_val)
            if len(b) != int(f["size"]):
                raise ValueError(f"fixed_bytes '{{name}}' length mismatch")
            chunks[name] = b
        elif kind == "fixed_str":
            raw_val = _require_field(obj, name)
            if not isinstance(raw_val, str):
                raise ValueError(f"fixed_str '{{name}}' must be str")
            raw = raw_val.encode(f.get("encoding", "utf-8"))
            pad = bytes.fromhex(f.get("pad_byte_hex", "00"))
            size = int(f["size"])
            if pad in raw or len(raw) > size:
                raise ValueError(f"fixed_str '{{name}}' invalid length or pad byte")
            chunks[name] = raw.ljust(size, pad)
        elif kind == "cstr":
            raw_val = _require_field(obj, name)
            if not isinstance(raw_val, str):
                raise ValueError(f"cstr '{{name}}' must be str")
            raw = raw_val.encode(f.get("encoding", "utf-8"))
            if b"\\x00" in raw:
                raise ValueError(f"cstr '{{name}}' contains embedded NUL")
            chunks[name] = raw + b"\\x00"
        elif kind == "var_str":
            raw_val = _require_field(obj, name)
            if not isinstance(raw_val, str):
                raise ValueError(f"var_str '{{name}}' must be str")
            chunks[name] = raw_val.encode(f.get("encoding", "utf-8"))
        elif kind in ("var_bytes", "bytes_rest"):
            raw_val = _require_field(obj, name)
            if not isinstance(raw_val, (bytes, bytearray)):
                raise ValueError(f"{{kind}} '{{name}}' must be bytes/bytearray")
            chunks[name] = bytes(raw_val)
        elif kind == "array":
            items_val = _require_field(obj, name)
            if not isinstance(items_val, list):
                raise ValueError(f"array '{{name}}' must be a list")
            chunks[name] = b"".join(_encode_fields(f["item_fields"], item) for item in items_val)
        else:
            raise ValueError(f"Unsupported field kind: {{kind}}")

    for f in fields:
        if f["kind"] == "scalar" and f.get("length_of"):
            width = _SCALAR_FMT[f["scalar_type"]][1]
            chunks[f["name"]] = b"\\x00" * width

    for f in reversed(fields):
        if f["kind"] == "scalar" and f.get("length_of"):
            targets = _resolve_span(fields, f["length_of"])
            total_len = sum(len(chunks[t]) for t in targets)
            chunks[f["name"]] = _pack_scalar(f, total_len)

    for f in fields:
        if f["kind"] == "scalar" and f.get("crc32_of"):
            targets = _resolve_span(fields, f["crc32_of"])
            covered = b"".join(chunks[t] for t in targets)
            crc = zlib.crc32(covered) & 0xFFFFFFFF
            chunks[f["name"]] = _pack_scalar(f, crc)

    return b"".join(chunks[f["name"]] for f in fields)


def decode(data: bytes) -> dict[str, Any]:
    if not isinstance(data, (bytes, bytearray, memoryview)):
        raise ValueError("Input data must be bytes-like")
    buf = bytes(data)
    out, pos = _decode_fields(SPEC_DICT["fields"], buf, 0)
    if pos != len(buf):
        raise ValueError(f"Unconsumed trailing bytes: {{len(buf) - pos}}")
    return out


def encode(obj: dict[str, Any]) -> bytes:
    return _encode_fields(SPEC_DICT["fields"], obj)
'''


def generate_python_module(spec: CodecSpec) -> str:
    validate_spec(spec)
    return _MODULE_TEMPLATE.format(spec_repr=repr(spec.to_dict()))
